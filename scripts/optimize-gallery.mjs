import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import sharp from "sharp"

const root = path.resolve(import.meta.dirname, "..")
const sourceDir = path.join(root, "public", "images")
const outDir = path.join(sourceDir, "gallery")
const manifestPath = path.join(root, "src", "data", "photoVariants.ts")

const files = [
  "01-hero.jpg",
  "02-portrait.jpg",
  "03-together.jpg",
  "04-candid.jpg",
  "05-details.jpg",
  "06-celebration.jpg",
]

const steps = [640, 960, 1280, 1600, 2048, 2560, 3200]

await mkdir(outDir, { recursive: true })

/** @type {Record<string, { width: number, height: number, sources: { width: number, webp: string, jpeg: string }[] }>} */
const manifest = {}

for (const file of files) {
  const sourcePath = path.join(sourceDir, file)
  const input = sharp(sourcePath, { failOn: "none" }).rotate()
  const meta = await input.metadata()
  const nativeWidth = meta.width ?? 0
  const nativeHeight = meta.height ?? 0
  if (!nativeWidth || !nativeHeight) throw new Error(`Could not read ${file}`)

  const widths = [...new Set(steps.filter((width) => width < nativeWidth).concat(Math.min(nativeWidth, 3200)))].sort(
    (a, b) => a - b,
  )
  const stem = file.replace(/\.jpe?g$/i, "")
  const sources = []

  for (const width of widths) {
    const webpName = `${stem}-${width}.webp`
    const jpegName = `${stem}-${width}.jpg`
    const pipeline = sharp(sourcePath, { failOn: "none" }).rotate().resize({
      width,
      withoutEnlargement: true,
      kernel: sharp.kernel.lanczos3,
      fastShrinkOnLoad: false,
    })
    const [webp, jpeg] = await Promise.all([
      pipeline
        .clone()
        .webp({ quality: 90, effort: 5, smartSubsample: false })
        .toFile(path.join(outDir, webpName)),
      pipeline
        .clone()
        .jpeg({
          quality: 90,
          mozjpeg: true,
          chromaSubsampling: width >= 1600 ? "4:4:4" : "4:2:0",
        })
        .toFile(path.join(outDir, jpegName)),
    ])
    sources.push({
      width: webp.width,
      webp: `/images/gallery/${webpName}`,
      jpeg: `/images/gallery/${jpegName}`,
    })
    console.log(
      `${file} ${nativeWidth}x${nativeHeight} -> ${webp.width}x${webp.height} webp ${webp.size}B jpeg ${jpeg.size}B`,
    )
  }

  manifest[`/images/${file}`] = { width: nativeWidth, height: nativeHeight, sources }
}

const body = `/* Generated by scripts/optimize-gallery.mjs. Do not edit by hand. */

export type PhotoSource = {
  width: number
  webp: string
  jpeg: string
}

export type PhotoVariantSet = {
  width: number
  height: number
  sources: PhotoSource[]
}

export const photoVariants: Record<string, PhotoVariantSet> = ${JSON.stringify(manifest, null, 2)}
`

await writeFile(manifestPath, body)
console.log(`Wrote ${manifestPath}`)
